package ch.plaintext.demo.h2;

import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Makes plaintext-root's Flyway migrations (written for PostgreSQL) run on H2 — at load time,
 * only for the demo's H2 database. The migration files themselves stay untouched, so a new root
 * version needs no copy. {@code H2MigrationRewriterTest} runs every migration on the classpath
 * through this class into a fresh H2 and fails as soon as root ships syntax not covered here.
 *
 * <p>The rules only cover what a fresh database needs:
 * <ul>
 *   <li>{@code DO $$ … $$;} blocks repair existing PostgreSQL databases. Their ALTER statements are
 *       kept, guarded by {@code IF EXISTS}, and translated where H2 differs; the procedural rest goes.</li>
 *   <li>Statements using PostgreSQL-only internals ({@code ctid}, {@code setval}, {@code split_part})
 *       only clean up old data and are dropped.</li>
 *   <li>{@code ON CONFLICT … DO NOTHING} is dropped: a fresh database has no conflicting rows.</li>
 *   <li>Partial indexes: a plain index loses its {@code WHERE}, a partial unique index is dropped
 *       (without the condition it would forbid re-creating a soft-deleted row).</li>
 * </ul>
 */
public final class H2MigrationRewriter {

    private static final Pattern DO_BLOCK = Pattern.compile("(?is)\\bDO\\s+\\$\\$(.*?)\\$\\$\\s*;");
    private static final Pattern EXECUTE = Pattern.compile("(?is)EXECUTE\\s+'((?:[^']|'')*)'\\s*;?");
    private static final Pattern ALTER_TABLE = Pattern.compile("(?is)\\bALTER\\s+TABLE\\s+[^;]+");
    /** H2 has no upsert clause; on a fresh database there is nothing to conflict with. DO UPDATE is left alone (fails loudly). */
    private static final Pattern ON_CONFLICT_DO_NOTHING = Pattern.compile("(?is)\\s+ON\\s+CONFLICT\\s*(\\([^)]*\\))?\\s*DO\\s+NOTHING");
    private static final Pattern PRIMARY_KEY = Pattern.compile("(?i)\\bPRIMARY\\s+KEY\\b");
    private static final Pattern PG_ONLY =Pattern.compile("(?is)\\bctid\\b|\\bsetval\\s*\\(|\\bpg_get_serial_sequence\\s*\\(|\\bsplit_part\\s*\\(");
    private static final Pattern PARTIAL_INDEX = Pattern.compile("(?is)^CREATE\\s+(UNIQUE\\s+)?INDEX\\b(.*?)\\s+WHERE\\s+.*$");
    private static final Pattern PARTIAL_INDEX_ANYWHERE = Pattern.compile("(?is)CREATE\\s+(UNIQUE\\s+)?INDEX\\b[^;]*\\bWHERE\\b");

    private H2MigrationRewriter() {
    }

    public static String rewrite(String sql) {
        String s = DO_BLOCK.matcher(sql).replaceAll(m -> Matcher.quoteReplacement(doBlock(m.group(1))));
        s = ON_CONFLICT_DO_NOTHING.matcher(s).replaceAll("");
        if (!PG_ONLY.matcher(s).find() && !PARTIAL_INDEX_ANYWHERE.matcher(s).find()) {
            return s;
        }
        StringBuilder out = new StringBuilder();
        for (String statement : s.replaceAll("(?m)--.*$", "").split(";")) {
            String t = statement.strip();
            if (t.isEmpty() || PG_ONLY.matcher(t).find()) {
                continue;
            }
            Matcher partial = PARTIAL_INDEX.matcher(t);
            if (partial.matches()) {
                if (partial.group(1) != null) {
                    continue;
                }
                t = "CREATE INDEX" + partial.group(2);
            }
            out.append(t).append(";\n");
        }
        return out.toString();
    }

    /** The ALTER TABLE statements of a DO block (plain or via EXECUTE '…'), made idempotent for H2. */
    private static String doBlock(String body) {
        List<String> statements = new ArrayList<>();
        Matcher execute = EXECUTE.matcher(body);
        while (execute.find()) {
            statements.add(execute.group(1).replace("''", "'"));
        }
        Matcher alter = ALTER_TABLE.matcher(EXECUTE.matcher(body).replaceAll(""));
        while (alter.find()) {
            statements.add(alter.group());
        }
        StringBuilder out = new StringBuilder("-- H2: DO block reduced to its ALTER statements\n");
        for (String st : statements) {
            // "add a primary key if there is none" cannot be expressed in H2; on a fresh database the
            // tables that need one got it in CREATE TABLE.
            if (ALTER_TABLE.matcher(st).lookingAt() && !PRIMARY_KEY.matcher(st).find()) {
                out.append(h2Alter(st.strip())).append(";\n");
            }
        }
        return out.toString();
    }

    static String h2Alter(String alter) {
        return alter
                .replaceAll("(?i)^ALTER\\s+TABLE\\s+(?!IF\\s+EXISTS)", "ALTER TABLE IF EXISTS ")
                .replaceAll("(?i)ALTER\\s+COLUMN\\s+(?!IF\\s+EXISTS)", "ALTER COLUMN IF EXISTS ")
                .replaceAll("(?i)DROP\\s+COLUMN\\s+(?!IF\\s+EXISTS)", "DROP COLUMN IF EXISTS ")
                .replaceAll("(?i)ADD\\s+COLUMN\\s+(?!IF\\s+NOT\\s+EXISTS)", "ADD COLUMN IF NOT EXISTS ")
                .replaceAll("(?i)ADD\\s+GENERATED\\s+BY\\s+DEFAULT\\s+AS\\s+IDENTITY", "SET GENERATED BY DEFAULT")
                .replaceAll("(?i)ADD\\s+GENERATED\\s+ALWAYS\\s+AS\\s+IDENTITY", "SET GENERATED ALWAYS");
    }
}
