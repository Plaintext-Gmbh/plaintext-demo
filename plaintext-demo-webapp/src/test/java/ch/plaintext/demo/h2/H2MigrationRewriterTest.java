package ch.plaintext.demo.h2;

import org.h2.tools.RunScript;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.Resource;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;

import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class H2MigrationRewriterTest {

    static final String H2_URL = "jdbc:h2:mem:%s;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DEFAULT_NULL_ORDERING=HIGH;"
            + "NON_KEYWORDS=KEY,VALUE,INDEX,TYPE,USER,YEAR,MONTH,DAY,VALUES,ROW,NUMBER";

    @Test
    void doBlockKeepsGuardedAlters() {
        String sql = """
                DO $$
                BEGIN
                    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'n' AND is_identity = 'YES') THEN
                        ALTER TABLE n ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
                    END IF;
                    IF EXISTS (SELECT 1 FROM x) THEN
                        EXECUTE 'ALTER TABLE u ALTER COLUMN k DROP NOT NULL';
                    END IF;
                END $$;
                SELECT setval(pg_get_serial_sequence('n', 'id'), 1, false);
                """;
        String h2 = H2MigrationRewriter.rewrite(sql);
        assertTrue(h2.contains("ALTER TABLE IF EXISTS n ALTER COLUMN IF EXISTS id SET GENERATED BY DEFAULT;"), h2);
        assertTrue(h2.contains("ALTER TABLE IF EXISTS u ALTER COLUMN IF EXISTS k DROP NOT NULL;"), h2);
        assertFalse(h2.contains("setval"), h2);
        assertFalse(h2.contains("$$"), h2);
    }

    @Test
    void partialIndexes() {
        String h2 = H2MigrationRewriter.rewrite("""
                CREATE INDEX IF NOT EXISTS i1 ON t (a) WHERE b IS NULL;
                CREATE UNIQUE INDEX IF NOT EXISTS i2 ON t (c) WHERE deleted = FALSE;
                CREATE TABLE z (id BIGINT);
                """);
        assertTrue(h2.contains("CREATE INDEX IF NOT EXISTS i1 ON t (a);"), h2);
        assertFalse(h2.contains("i2"), h2);
        assertTrue(h2.contains("CREATE TABLE z (id BIGINT);"), h2);
    }

    @Test
    void plainScriptStaysByteIdentical() {
        String sql = "-- comment; with semicolon\nCREATE TABLE a (id BIGSERIAL, v VARCHAR(10) DEFAULT 'x;y');\n";
        assertEquals(sql, H2MigrationRewriter.rewrite(sql));
    }

    /** The guard for the workbench: every migration on the classpath (root + demo) must run on H2. */
    @Test
    void everyMigrationOnTheClasspathRunsOnH2() throws Exception {
        List<Resource> scripts = new ArrayList<>(Arrays.asList(
                new PathMatchingResourcePatternResolver().getResources("classpath*:db/migration/*.sql")));
        scripts.sort(Comparator.comparing(H2MigrationRewriterTest::version, H2MigrationRewriterTest::compareVersions));
        assertTrue(scripts.size() > 40, "root-Migrationen nicht auf dem Klassenpfad: " + scripts.size());
        List<String> fehler = new ArrayList<>();
        try (Connection c = DriverManager.getConnection(H2_URL.formatted("alle"), "sa", "")) {
            for (Resource r : scripts) {
                try {
                    RunScript.execute(c, new StringReader(H2MigrationRewriter.rewrite(r.getContentAsString(StandardCharsets.UTF_8))));
                } catch (Exception e) {
                    fehler.add(r.getFilename() + ": " + e.getMessage().lines().findFirst().orElse(""));
                }
            }
            try (ResultSet rs = c.createStatement().executeQuery(
                    "SELECT is_nullable FROM information_schema.columns WHERE table_name = 'my_user_entity' AND column_name = 'autologin_key'")) {
                assertFalse(rs.next() && "NO".equals(rs.getString(1)), "autologin_key darf nicht NOT NULL bleiben");
            }
        }
        assertEquals(List.of(), fehler, "Migrationen, die auf H2 scheitern");
    }

    private static String version(Resource r) {
        Matcher m = Pattern.compile("^V([0-9._]+)__").matcher(r.getFilename());
        return m.find() ? m.group(1) : "0";
    }

    private static int compareVersions(String a, String b) {
        String[] x = a.split("[._]");
        String[] y = b.split("[._]");
        for (int i = 0; i < Math.max(x.length, y.length); i++) {
            long p = i < x.length ? Long.parseLong(x[i]) : 0;
            long q = i < y.length ? Long.parseLong(y[i]) : 0;
            if (p != q) {
                return Long.compare(p, q);
            }
        }
        return 0;
    }
}
